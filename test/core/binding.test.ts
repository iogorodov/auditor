import { test, expect, describe } from 'bun:test';
import { remarkApplies } from '../../src/core/binding.ts';

// Шаблонные листья реальной иерархии:
//   Документация → [Здание, Другое]
//   Общее        → [Другое]
//   Помещение    → [Помещение(fixed), Щит / панель]

describe('remarkApplies (§3.2)', () => {
  test('пустая привязка = применимо везде', () => {
    expect(remarkApplies([], 'Щит / панель', 'Помещение')).toBe(true);
    expect(remarkApplies([], 'Здание', 'Документация')).toBe(true);
  });

  test('«Документация» попадает во все листья под Документацией через родителя', () => {
    expect(remarkApplies(['Документация'], 'Здание', 'Документация')).toBe(true);
    expect(remarkApplies(['Документация'], 'Другое', 'Документация')).toBe(true);
    // но не в «Другое» под «Общее»
    expect(remarkApplies(['Документация'], 'Другое', 'Общее')).toBe(false);
  });

  test('«Щит / панель» — только в щитах (совпадение по листу)', () => {
    expect(remarkApplies(['Щит / панель'], 'Щит / панель', 'Помещение')).toBe(true);
    expect(remarkApplies(['Щит / панель'], 'Помещение', 'Помещение')).toBe(false);
  });

  test('«Помещение» — и фикс-лист Помещение, и все щиты (через родителя)', () => {
    // совпадение по имени листа
    expect(remarkApplies(['Помещение'], 'Помещение', 'Помещение')).toBe(true);
    // совпадение по имени родителя (родитель щита — слот «Помещение»)
    expect(remarkApplies(['Помещение'], 'Щит / панель', 'Помещение')).toBe(true);
    // но не в документации
    expect(remarkApplies(['Помещение'], 'Здание', 'Документация')).toBe(false);
  });

  test('составная привязка «Помещение; Щит / панель»', () => {
    const b = ['Помещение', 'Щит / панель'];
    expect(remarkApplies(b, 'Помещение', 'Помещение')).toBe(true);
    expect(remarkApplies(b, 'Щит / панель', 'Помещение')).toBe(true);
    expect(remarkApplies(b, 'Здание', 'Документация')).toBe(false);
  });

  test('сравнение без учёта регистра и пробелов', () => {
    expect(remarkApplies([' щит / ПАНЕЛЬ '], 'Щит / панель', 'Помещение')).toBe(true);
  });
});
